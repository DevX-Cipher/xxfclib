/*
 * Private, target-width PEB field metadata for concrete Windows releases.
 * These arrays describe bytes in the target process; they are not host structs.
 * Layout facts were independently transcribed into original descriptor code.
 * All union alternatives intentionally overlap. Array types retain their element
 * counts. AlignmentPadding names describe unnamed ABI gaps, not discovered data.
 *
 * Concrete symbol-derived layouts (consulted 2026-10-20):
 * https://www.vergiliusproject.com/kernels/x64/windows-10/22h2/_PEB
 * https://www.vergiliusproject.com/kernels/x64/windows-10/22h2/_PEB32
 * https://www.vergiliusproject.com/kernels/x86/windows-10/22h2/_PEB
 * https://www.vergiliusproject.com/kernels/x64/windows-11/24h2/_PEB
 * https://www.vergiliusproject.com/kernels/x64/windows-11/24h2/_PEB32
 * PEB32 is the symbol-derived WOW64 companion layout on x64, including Windows 11.
 * Build 19045 also matches native x86 PEB member offsets, sizes and array counts;
 * its UNICODE_STRING and the WOW64 STRING32 share the same 8-byte string ABI.
 * These profiles do not assert compatibility with unlisted builds or ARM64.
 *
 * Field semantics and NtGlobalFlags masks were cross-checked against phnt:
 * https://github.com/winsiderss/phnt/blob/master/ntpebteb.h
 * https://github.com/winsiderss/phnt/blob/master/LICENSE (MIT)
 * No third-party structure declarations or explanatory comments are copied.
 * The concrete profile's original member names take precedence where current
 * phnt uses a newer name (for example pUnused/Spare/EcCodeBitMap).
 *
 * Include after xx_data_struct_field_desc, XX_PSW_FIELD, XX_PSW_PTR,
 * XX_PSW_RESERVED, XX_PSW_SIZE, XX_PSW_ID and property enums are declared.
 * A bitfield:SHIFT:BITS type uses the physical parent-storage byte span; the
 * decoder preserves those raw bytes and extracts only the specified bits for
 * display. Dotted member names distinguish nested storage and union aliases.
 */
