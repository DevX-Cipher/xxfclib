/*
 * Original explicit target-layout metadata for legacy NT HEAP records.
 * Include after xx_psw_target/xx_psw_nt_layout and the XX_PSW_* macros.
 * No host structure layout, allocator walk or heap pointer decoding is used.
 *
 * Concrete symbol profiles, consulted 2026-10-20:
 * https://www.vergiliusproject.com/kernels/x86/windows-10/22h2/_HEAP
 * https://www.vergiliusproject.com/kernels/x64/windows-10/22h2/_HEAP
 * https://www.vergiliusproject.com/kernels/x64/windows-11/24h2/_HEAP
 * The corresponding _HEAP_ENTRY, _HEAP_UNPACKED_ENTRY, _HEAP_EXTENDED_ENTRY
 * and _HEAP_COUNTERS pages provide the entry overlays and nested counter spans.
 * https://www.vergiliusproject.com/kernels/x86/windows-10/22h2/_HEAP_TUNING_PARAMETERS
 * https://www.vergiliusproject.com/kernels/x86/windows-10/22h2/_RTL_HEAP_MEMORY_LIMIT_DATA
 * https://www.vergiliusproject.com/kernels/x64/windows-10/22h2/_RTL_HEAP_MEMORY_LIMIT_DATA
 * https://www.vergiliusproject.com/kernels/x64/windows-11/24h2/_RTLP_HEAP_COMMIT_LIMIT_DATA
 * Primary declarations corroborating signatures, tuning member types and the
 * Windows 11 RTLP_HEAP_COMMIT_LIMIT_DATA member types:
 * https://github.com/winsiderss/systeminformer/blob/master/SystemInformer/include/heapstruct.h
 * Run-once opaque storage:
 * https://github.com/winsiderss/phnt/blob/master/ntrtl.h
 *
 * Only factual names, offsets, sizes and masks were transcribed into this
 * original code. No third-party declarations or explanatory prose are copied.
 *
 * This header covers native I386 19045 and AMD64 19045/26100 only. There is
 * no proven complete WOW64 HEAP32 profile here; matching pointer width is not
 * sufficient to select one. ARM64/emulated private layouts are not inferred.
 *
 * Entry/Encoding union alternatives intentionally overlap. The descriptors
 * expose their physical raw storage, not a decoded allocation header. Opaque,
 * encoded and tagged values do not carry POINTER/VIRTUAL_ADDRESS properties.
 * CommitRoutine is opaque metadata and is never invoked. Ordinary list pointers
 * are described for display only; this module never follows allocator links.
 * CommitLimitData retains the complete raw parent and its version-specific
 * named fields: four limit-data members on 19045, two commit-data members on
 * 26100. Failure-code storage is displayed as flags, not followed as a pointer.
 * AlignmentPadding labels describe unnamed ABI gaps.
 */
